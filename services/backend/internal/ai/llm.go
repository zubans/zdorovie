// RecommendTemplate picks the closest clinical template based on patient context, question, notes, or transcript.
func RecommendTemplate(ctx context.Context, cfg config.Config, templates []db.SummaryTemplate, contextText, pregStatus string) (string, string) {
	if len(templates) == 0 {
		return "", ""
	}
	combined := strings.ToLower(strings.TrimSpace(contextText + " " + pregStatus))

	// Try external LLM classification when live provider is configured and we have rich context.
	provider := strings.ToLower(strings.TrimSpace(cfg.LLMProvider))
	if (provider == "yandexgpt" || provider == "gigachat") && strings.TrimSpace(contextText) != "" {
		if code, reason, err := recommendTemplateViaLLM(ctx, cfg, templates, MaskPII(combined)); err == nil && code != "" {
			return code, reason
		}
	}

	bestCode := templates[0].Code
	bestTitle := templates[0].Title
	bestScore := -1
	var matchedKeywords []string

	for _, tpl := range templates {
		score := 0
		var hits []string
		for _, kw := range strings.Split(tpl.Keywords, ",") {
			k := strings.TrimSpace(strings.ToLower(kw))
			if k != "" && strings.Contains(combined, k) {
				score += 3
				hits = append(hits, k)
			}
		}
		// Trimester heuristics from pregnancy_status like "22 нед."
		weeks := extractWeeks(pregStatus)
		switch {
		case weeks >= 1 && weeks <= 13 && tpl.Code == "first_trimester_adaptation":
			score += 2
		case weeks >= 14 && weeks <= 27 && (tpl.Code == "anemia_ferritin" || tpl.Code == "nutrition_gdm"):
			score += 1
		case weeks >= 28 && weeks <= 42 && tpl.Code == "birth_preparation":
			score += 2
		case strings.Contains(strings.ToLower(pregStatus), "после родов") && tpl.Code == "postpartum_recovery":
			score += 4
		}

		if score > bestScore {
			bestScore = score
			bestCode = tpl.Code
			bestTitle = tpl.Title
			matchedKeywords = hits
		}
	}

	if bestScore <= 0 {
		return templates[0].Code, fmt.Sprintf("Базовый подбор для «%s»", templates[0].Title)
	}
	if len(matchedKeywords) > 0 {
		limit := len(matchedKeywords)
		if limit > 3 {
			limit = 3
		}
		return bestCode, fmt.Sprintf("Подобрано ИИ («%s» по ключевым признакам: %s)", bestTitle, strings.Join(matchedKeywords[:limit], ", "))
	}
	return bestCode, fmt.Sprintf("Подобрано ИИ по сроку/контексту («%s»)", bestTitle)
}

func extractWeeks(pregStatus string) int {
	re := regexp.MustCompile(`\d{1,2}`)
	m := re.FindString(pregStatus)
	if m == "" {
		return 0
	}
	w, _ := strconv.Atoi(m)
	return w
}

// GenerateConclusionFromDescription builds a structured medical conclusion from doctor's free-form notes,
// chosen template, and optional Whisper transcript.
func GenerateConclusionFromDescription(
	ctx context.Context,
	cfg config.Config,
	tpl *db.SummaryTemplate,
	doctorDescription, transcriptText, patientQuestion, pregStatus, clientName string,
) (GeneratedConclusion, error) {
	maskedDesc := MaskPII(strings.TrimSpace(doctorDescription), clientName)
	maskedTranscript := MaskPII(strings.TrimSpace(transcriptText), clientName)
	maskedQuestion := MaskPII(strings.TrimSpace(patientQuestion), clientName)

	tplTitle := "Без шаблона"
	tplCode := ""
	if tpl != nil {
		tplTitle = tpl.Title
		tplCode = tpl.Code
	}

	provider := strings.ToLower(strings.TrimSpace(cfg.LLMProvider))
	if provider == "yandexgpt" || provider == "gigachat" {
		sysPrompt := "Ты медицинский ИИ-ассистент врача (акушерство, терапия, нутрициология беременности). На основе заметок врача, выбранного клинического шаблона и фрагментов приёма сформируй строго JSON-объект с полями: complaints, anamnesis, recommendations, diagnostics_plan, follow_up. Пиши структурированно на русском языке, без выдумывания диагнозов и без персональных данных."
		userPrompt := fmt.Sprintf("Срок/статус: %s\nШаблон: %s\nЗапрос до приёма: %s\nОписание врача: %s\nФрагменты стенограммы:\n%s",
			pregStatus, tplTitle, maskedQuestion, maskedDesc, limitRunes(maskedTranscript, 3500))
		if raw, modelName, err := callConfiguredLLM(ctx, cfg, sysPrompt, userPrompt); err == nil {
			var parsed GeneratedConclusion
			if jsonErr := parseLooseJSON(raw, &parsed); jsonErr == nil && strings.TrimSpace(parsed.Recommendations) != "" {
				parsed.TemplateCode = tplCode
				parsed.LLMModelName = modelName
				return parsed, nil
			}
		}
	}

	// Deterministic local AI synthesis preserving doctor description + template
	complaints := maskedQuestion
	if complaints == "" && tpl != nil {
		complaints = tpl.ComplaintsTpl
	}
	if complaints == "" {
		complaints = "Индивидуальная консультация по ведению беременности и поддержке здоровья."
	}

	anamnesis := ""
	if tpl != nil {
		anamnesis = tpl.AnamnesisTpl
	}
	if pregStatus != "" {
		anamnesis = fmt.Sprintf("Срок / статус: %s. %s", pregStatus, strings.TrimSpace(anamnesis))
	}
	if maskedDesc != "" {
		if anamnesis != "" {
			anamnesis += "\n"
		}
		anamnesis += "Клинические заметки врача: " + limitRunes(maskedDesc, 500)
	}

	var recParts []string
	if maskedDesc != "" {
		recParts = append(recParts, "Ключевые акценты по итогам приёма:\n• "+strings.ReplaceAll(strings.TrimSpace(maskedDesc), "\n", "\n• "))
	}
	if tpl != nil && strings.TrimSpace(tpl.RecommendationsTpl) != "" {
		recParts = append(recParts, tpl.RecommendationsTpl)
	}
	if maskedTranscript != "" {
		recParts = append(recParts, "Дополнение по ходу беседы: учесть обсуждённые симптомы и текущую переносимость нутриентов.")
	}
	if len(recParts) == 0 {
		recParts = append(recParts, "1. Сбалансированное питание с достаточным содержанием белка и микронутриентов.\n2. Наблюдение динамики самочувствия и плановый контакт с лечащим врачом.")
	}

	diagnostics := "ОАК, ферритин, ОАМ, ТТГ и 25(OH)D по сроку беременности."
	followUp := "Повторная оценка состояния и анализов через 2–4 недели."
	if tpl != nil {
		if tpl.DiagnosticsTpl != "" {
			diagnostics = tpl.DiagnosticsTpl
		}
		if tpl.FollowUpTpl != "" {
			followUp = tpl.FollowUpTpl
		}
	}

	modelLabel := "mock-clinical-synthesizer"
	if provider != "" && provider != "mock" {
		modelLabel = provider + "-fallback"
	}

	return GeneratedConclusion{
		TemplateCode:    tplCode,
		LLMModelName:    modelLabel,
		Complaints:      strings.TrimSpace(complaints),
		Anamnesis:       strings.TrimSpace(anamnesis),
		Recommendations: strings.TrimSpace(strings.Join(recParts, "\n\n")),
		DiagnosticsPlan: strings.TrimSpace(diagnostics),
		FollowUp:        strings.TrimSpace(followUp),
	}, nil
}

