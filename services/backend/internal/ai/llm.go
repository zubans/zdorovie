func recommendTemplateViaLLM(ctx context.Context, cfg config.Config, templates []db.SummaryTemplate, contextText string) (string, string, error) {
	var options []string
	for _, t := range templates {
		options = append(options, fmt.Sprintf("%s: %s (%s)", t.Code, t.Title, t.Category))
	}
	sys := `Выбери наиболее подходящий code шаблона из списка и верни JSON {"code":"...","reason":"..."}`
	user := fmt.Sprintf("Шаблоны:\n%s\n\nКонтекст:\n%s", strings.Join(options, "\n"), limitRunes(contextText, 2000))
	raw, _, err := callConfiguredLLM(ctx, cfg, sys, user)
	if err != nil {
		return "", "", err
	}
	var out struct {
		Code   string `json:"code"`
		Reason string `json:"reason"`
	}
	if err := parseLooseJSON(raw, &out); err != nil || out.Code == "" {
		return "", "", fmt.Errorf("invalid llm template output")
	}
	for _, t := range templates {
		if t.Code == out.Code {
			return out.Code, nonEmpty(out.Reason, "Подобрано ИИ: "+t.Title), nil
		}
	}
	return "", "", fmt.Errorf("unknown code")
}

func callConfiguredLLM(ctx context.Context, cfg config.Config, sysPrompt, userPrompt string) (string, string, error) {
	provider := strings.ToLower(strings.TrimSpace(cfg.LLMProvider))
	switch provider {
	case "yandexgpt":
		if cfg.YandexGPTAPIKey == "" || cfg.YandexGPTFolderID == "" {
			return "", "", fmt.Errorf("yandexgpt credentials not set")
		}
		text, err := callYandexGPT(ctx, cfg.YandexGPTAPIKey, cfg.YandexGPTFolderID, sysPrompt, userPrompt)
		return text, "yandexgpt/latest", err
	case "gigachat":
		if cfg.GigaChatAuthKey == "" {
			return "", "", fmt.Errorf("gigachat credentials not set")
		}
		text, err := callGigaChat(ctx, cfg.GigaChatAuthKey, sysPrompt, userPrompt)
		return text, "GigaChat", err
	default:
		return "", "mock", fmt.Errorf("mock provider")
	}
}

func callYandexGPT(ctx context.Context, apiKey, folderID, sysPrompt, userPrompt string) (string, error) {
	payload := map[string]interface{}{
		"modelUri": fmt.Sprintf("gpt://%s/yandexgpt/latest", folderID),
		"completionOptions": map[string]interface{}{
			"stream":      false,
			"temperature": 0.2,
			"maxTokens":   1600,
		},
		"messages": []map[string]string{
			{"role": "system", "text": sysPrompt},
			{"role": "user", "text": userPrompt},
		},
	}
	raw, _ := json.Marshal(payload)
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, "https://llm.api.cloud.yandex.net/foundationModels/v1/completion", bytes.NewReader(raw))
	if err != nil {
		return "", err
	}
	req.Header.Set("Authorization", "Api-Key "+apiKey)
	req.Header.Set("x-folder-id", folderID)
	req.Header.Set("Content-Type", "application/json")

	client := &http.Client{Timeout: 35 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if resp.StatusCode >= 300 {
		return "", fmt.Errorf("yandexgpt status %d: %s", resp.StatusCode, string(body))
	}
	var res struct {
		Result struct {
			Alternatives []struct {
				Message struct {
					Text string `json:"text"`
				} `json:"message"`
			} `json:"alternatives"`
		} `json:"result"`
	}
	if err := json.Unmarshal(body, &res); err != nil || len(res.Result.Alternatives) == 0 {
		return "", fmt.Errorf("unexpected yandexgpt response")
	}
	return res.Result.Alternatives[0].Message.Text, nil
}

func callGigaChat(ctx context.Context, authKey, sysPrompt, userPrompt string) (string, error) {
	form := url.Values{}
	form.Set("scope", "GIGACHAT_API_PERS")
	oauthReq, err := http.NewRequestWithContext(ctx, http.MethodPost, "https://ngw.devices.sberbank.ru:9443/api/v2/oauth", strings.NewReader(form.Encode()))
	if err != nil {
		return "", err
	}
	oauthReq.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	oauthReq.Header.Set("Accept", "application/json")
	oauthReq.Header.Set("RqUID", fmt.Sprintf("%d", time.Now().UnixNano()))
	oauthReq.Header.Set("Authorization", "Basic "+authKey)

	// GigaChat Russian Trusted Root CA may not be present in minimal alpine images
	client := &http.Client{
		Timeout: 35 * time.Second,
		Transport: &http.Transport{
			TLSClientConfig: &tls.Config{InsecureSkipVerify: true},
		},
	}
	oauthResp, err := client.Do(oauthReq)
	if err != nil {
		return "", err
	}
	defer oauthResp.Body.Close()
	oauthBody, _ := io.ReadAll(io.LimitReader(oauthResp.Body, 256<<10))
	if oauthResp.StatusCode >= 300 {
		return "", fmt.Errorf("gigachat oauth %d", oauthResp.StatusCode)
	}
	var tokenRes struct {
		AccessToken string `json:"access_token"`
	}
	if err := json.Unmarshal(oauthBody, &tokenRes); err != nil || tokenRes.AccessToken == "" {
		return "", fmt.Errorf("gigachat token parse failed")
	}

	chatPayload := map[string]interface{}{
		"model":       "GigaChat",
		"temperature": 0.2,
		"messages": []map[string]string{
			{"role": "system", "content": sysPrompt},
			{"role": "user", "content": userPrompt},
		},
	}
	raw, _ := json.Marshal(chatPayload)
	chatReq, err := http.NewRequestWithContext(ctx, http.MethodPost, "https://gigachat.devices.sberbank.ru/api/v1/chat/completions", bytes.NewReader(raw))
	if err != nil {
		return "", err
	}
	chatReq.Header.Set("Authorization", "Bearer "+tokenRes.AccessToken)
	chatReq.Header.Set("Content-Type", "application/json")

	chatResp, err := client.Do(chatReq)
	if err != nil {
		return "", err
	}
	defer chatResp.Body.Close()
	chatBody, _ := io.ReadAll(io.LimitReader(chatResp.Body, 1<<20))
	if chatResp.StatusCode >= 300 {
		return "", fmt.Errorf("gigachat chat %d", chatResp.StatusCode)
	}
	var res struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.Unmarshal(chatBody, &res); err != nil || len(res.Choices) == 0 {
		return "", fmt.Errorf("unexpected gigachat response")
	}
	return res.Choices[0].Message.Content, nil
}

func parseLooseJSON(raw string, dst interface{}) error {
	cleaned := strings.TrimSpace(raw)
	cleaned = strings.TrimPrefix(cleaned, "```json")
	cleaned = strings.TrimPrefix(cleaned, "```")
	cleaned = strings.TrimSuffix(cleaned, "```")
	cleaned = strings.TrimSpace(cleaned)
	start := strings.Index(cleaned, "{")
	end := strings.LastIndex(cleaned, "}")
	if start >= 0 && end > start {
		cleaned = cleaned[start : end+1]
	}
	return json.Unmarshal([]byte(cleaned), dst)
}

func limitRunes(s string, max int) string {
	r := []rune(s)
	if len(r) <= max {
		return s
	}
	return string(r[:max]) + "..."
}

func nonEmpty(s, fallback string) string {
	if strings.TrimSpace(s) == "" {
		return fallback
	}
	return s
}
